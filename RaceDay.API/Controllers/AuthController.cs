
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using RaceDay.API.Data;
using RaceDay.API.DTOs;
using RaceDay.API.Models;
using RaceDay.API.Services;

namespace RaceDay.API.Controllers
{
    [ApiController]
    [Route("api/[controller]")]
    public class AuthController : ControllerBase
    {
        private readonly RaceDayDbContext _context;
        private readonly PasswordService _passwordService;
        private readonly TokenService _tokenService;

        public AuthController(
            RaceDayDbContext context,
            PasswordService passwordService,
            TokenService tokenService)
        {
            _context = context;
            _passwordService = passwordService;
            _tokenService = tokenService;
        }

        [HttpPost("register/participant")]
        public async Task<IActionResult> RegisterParticipant(
            [FromBody] RegisterRequest request)
        {
            if (request == null ||
                string.IsNullOrWhiteSpace(request.Name) ||
                string.IsNullOrWhiteSpace(request.Surname) ||
                string.IsNullOrWhiteSpace(request.Email) ||
                string.IsNullOrWhiteSpace(request.Password))
            {
                return BadRequest(new
                {
                    success = false,
                    message = "Complete all registration fields."
                });
            }

            string email = request.Email.Trim();

            bool exists = await _context.Participants
                .AnyAsync(p => p.Email == email);

            if (exists)
            {
                return Conflict(new
                {
                    success = false,
                    message = "Email already registered."
                });
            }

            var participant = new Participant
            {
                ParticipantName = request.Name.Trim(),
                ParticipantSurname = request.Surname.Trim(),
                Email = email,
                PasswordHash = _passwordService.HashPassword(
                    request.Password)
            };

            _context.Participants.Add(participant);
            await _context.SaveChangesAsync();

            return Ok(new
            {
                success = true,
                message = "Participant registered successfully."
            });
        }

        [HttpPost("register/organiser")]
        public async Task<IActionResult> RegisterOrganiser(
            [FromBody] RegisterRequest request)
        {
            if (request == null ||
                string.IsNullOrWhiteSpace(request.Name) ||
                string.IsNullOrWhiteSpace(request.Surname) ||
                string.IsNullOrWhiteSpace(request.Email) ||
                string.IsNullOrWhiteSpace(request.Password))
            {
                return BadRequest(new
                {
                    success = false,
                    message = "Complete all registration fields."
                });
            }

            string email = request.Email.Trim();

            bool exists = await _context.Organisers
                .AnyAsync(o => o.Email == email);

            if (exists)
            {
                return Conflict(new
                {
                    success = false,
                    message = "Email already registered."
                });
            }

            var organiser = new Organiser
            {
                Name = $"{request.Name.Trim()} {request.Surname.Trim()}",
                Email = email,
                PasswordHash = _passwordService.HashPassword(
                    request.Password),
                CreatedAT = DateTime.UtcNow
            };

            // OrganiserID is generated by SQL Server.
            _context.Organisers.Add(organiser);
            await _context.SaveChangesAsync();

            return Ok(new
            {
                success = true,
                message = "Organiser registered successfully."
            });
        }

        [HttpPost("login")]
        public async Task<IActionResult> Login(
            [FromBody] LoginRequest request)
        {
            if (request == null ||
                string.IsNullOrWhiteSpace(request.Email) ||
                string.IsNullOrWhiteSpace(request.Password) ||
                string.IsNullOrWhiteSpace(request.Role))
            {
                return BadRequest(new
                {
                    success = false,
                    message = "Enter email, password and account type."
                });
            }

            string email = request.Email.Trim();
            string role = request.Role.Trim();

            string? userId = null;
            string? storedHash = null;
            string? userName = null;

            if (role.Equals("Participant",
                StringComparison.OrdinalIgnoreCase))
            {
                var participant = await _context.Participants
                    .FirstOrDefaultAsync(p => p.Email == email);

                if (participant != null)
                {
                    userId = participant.ParticipantID.ToString();
                    storedHash = participant.PasswordHash;
                    userName = participant.ParticipantName;
                }
            }
            else if (role.Equals("Organiser",
                StringComparison.OrdinalIgnoreCase))
            {
                var organiser = await _context.Organisers
                    .FirstOrDefaultAsync(o => o.Email == email);

                if (organiser != null)
                {
                    userId = organiser.OrganiserID.ToString();
                    storedHash = organiser.PasswordHash;
                    userName = organiser.Name;
                }
            }
            else
            {
                return BadRequest(new
                {
                    success = false,
                    message = "Invalid account type."
                });
            }

            if (userId == null ||
                string.IsNullOrWhiteSpace(storedHash) ||
                !_passwordService.VerifyPassword(
                    storedHash, request.Password))
            {
                return Unauthorized(new
                {
                    success = false,
                    message = "Invalid email, password or account type."
                });
            }

            string token = _tokenService.GenerateToken(
                userId, email, role);

            return Ok(new
            {
                success = true,
                message = "Login successful.",
                userId,
                userName,
                email,
                role,
                token
            });
        }
    }
}
